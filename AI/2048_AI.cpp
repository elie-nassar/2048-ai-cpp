int score_heuristic(const std::vector<std::vector<int>> tiles) {
    std::vector<int> scores(8,0);
    int max_score = 0;
    for(int i=0;i<4;i++) {
        for(int j=0;j<4;j++) {
            for(int k=0;k<8;k++) {
                scores[k]+=tiles[i][j]*bestboards[k][i][j];
                if(max_score<scores[k]) max_score = scores[k];
            }
        }
    }
    return max_score;
}

